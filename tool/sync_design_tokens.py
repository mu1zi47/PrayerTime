#!/usr/bin/env python3
"""Sync native colors and icon vector colors from the Flutter palette."""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = (ROOT / 'lib/theme/app_colors.dart').read_text()
RESOURCES = ROOT / 'android/app/src/main/res'

def palette(theme):
    block = SOURCE.split(f'const _{theme} = AppPalette(', 1)[1].split('\n);', 1)[0]
    return dict(re.findall(r'(\w+): Color\(0xFF([0-9A-F]{6})\)', block))

colors = {}
for theme in ['light', 'dark']:
    values = palette(theme)
    for role, field in {
        'accent': 'accent700',
        'brand': 'accent',
        'control': 'controlFill',
        'on_control': 'onControlFill',
        'secondary': 'accent2',
        'background': 'bg',
        'glow': 'accent',
        'text': 'text',
        'surface': 'surface',
        'badge': 'accent100',
        'chip': 'neutral600',
    }.items():
        colors[f'app_ds_{theme}_{role}'] = values[field]

# Alpha variants are also derived, so XML never repeats RGB values.
lines = ['<?xml version="1.0" encoding="utf-8"?>',
         '<!-- Generated by tool/sync_design_tokens.py from lib/theme/app_colors.dart. -->',
         '<resources>']
for name, rgb in colors.items():
    lines.append(f'    <color name="{name}">#{rgb}</color>')
    for alpha in ['00', '05', '0D', '14', '1A', '1F', '29', '33', '40', '4D', '66', '8F', 'CC']:
        lines.append(f'    <color name="{name}_{alpha.lower()}">#{alpha}{rgb}</color>')
# Native Now Bar uses the same panel radius and text hierarchy as Flutter.
tokens = (ROOT / 'lib/theme/app_tokens.dart').read_text()
font_sizes = tokens.split('abstract final class AppFontSize {', 1)[1].split('}', 1)[0]
radii = SOURCE.split('class AppRadius {', 1)[1].split('}', 1)[0]
for name, block, field, unit in [
    ('app_ds_panel_radius', radii, 'lg', 'dp'),
    ('app_ds_text_title', font_sizes, 'title', 'dp'),
    ('app_ds_text_heading', font_sizes, 'heading', 'dp'),
    ('app_ds_text_display', font_sizes, 'display', 'dp'),
    ('app_ds_text_body', font_sizes, 'body', 'dp'),
]:
    value = re.search(r'static const ' + field + r' = ([0-9.]+);', block).group(1)
    lines.append(f'    <dimen name="{name}">{value}{unit}</dimen>')
lines.append('</resources>')
(RESOURCES / 'values/app_design_tokens.xml').write_text('\n'.join(lines) + '\n')

# Icon sources use semantic roles, just like the Flutter application.
ET.register_namespace('', 'http://www.w3.org/2000/svg')
dark = palette('dark')
for filename in ['icon.svg', 'mark.svg', 'background.svg']:
    path = ROOT / 'assets/icon' / filename
    tree = ET.parse(path)
    for element in tree.iter():
        role = element.get('data-color')
        if role:
            attribute = 'stop-color' if element.tag.endswith('}stop') else 'fill'
            element.set(attribute, '#' + dark[role])
    ET.indent(tree, space='  ')
    tree.write(path, encoding='unicode')
    path.write_text(path.read_text() + '\n')
config = ROOT / 'flutter_launcher_icons.yaml'
text = config.read_text()
for key, role in [('background_color', 'bg'), ('theme_color', 'accent')]:
    text = re.sub(r'(' + key + r':\s*)"#[0-9A-Fa-f]{6}"',
                  lambda match: match[1] + '"#' + dark[role] + '"', text)
config.write_text(text)
